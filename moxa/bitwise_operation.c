#include <stdio.h>

int main(int argc, char *argv[])
{
    long ans = 0;
    // 0001001000110100
    short a = 0x1234;
    // 0101011000000000
    short b = 0x5600;
    ans += a << 16;
    ans += b << 0;
    // 00010010001101000101011000000000
    // +                 01010110000000
    // +                       00100010
    // --------------------------------
    // 00010010001101000110101110100010
    ans += (b >> 2) + 0x22;
    printf("%ld\n", ans);
    return 0;
}
